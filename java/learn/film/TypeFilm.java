package hnp.project.demoactivemq.test.film;

public class TypeFilm {
    String code;
    String type;

    public TypeFilm(String code, String type) {
        this.code = code;
        this.type = type;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }
}
